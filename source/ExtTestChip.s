IRQ1_HANDLER:
	cmpi.l #CHK_IRQ_MAGIC_VAL,(CHK_IRQ_MAGIC).l
	bne EXC_INTERRUPT
	addq.w #1,(CHK_VBL_COUNT).l
	move.w #4,(REG_IRQACK).l
	rte

