#!/usr/bin/env python3
"""Writes emulator/m68k_tables.py: for each of the 65536 opcodes, the Musashi handler and its
68000 cycle count, taken from Musashi itself (m68ki_build_opcode_table), so the Python 68000
decodes and counts exactly like the C core.

Handlers that are not 68000 instructions are folded into what Musashi does with them on a
68000: "x_illegal" (illegal instruction exception) or "x_1111" (line F exception); MOVE16 and
RESET keep their own names (Musashi runs MOVE16 on any CPU). Their cycle count stays 0, as in
Musashi (the exception counts its own).

Needs the Musashi clone of build_core.py (emulator/build/src, after a core build) and gcc.
Usage: python3 emulator/build_m68k_tables.py
"""
import base64, lzma, re, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "build" / "src"


def strip_guards(body):
    """The body without its 'if(CPU_TYPE_IS_...(CPU_TYPE)) {...}' blocks: what a 68000 runs."""
    out, i = "", 0
    while True:
        m = re.search(r'if\s*\(\s*CPU_TYPE_IS_\w+\(CPU_TYPE\)\s*\)\s*\{', body[i:])
        if not m:
            return re.sub(r"\s+", " ", out + body[i:]).strip()
        out += body[i:i + m.start()]
        j, depth = i + m.end(), 1
        while depth:
            depth += {"{": 1, "}": -1}.get(body[j], 0)
            j += 1
        i = j


def main():
    if not (SRC / "m68kops.c").is_file():
        sys.exit("emulator/build/src/m68kops.c missing: run emulator/build_core.py (or build_test_core.py) first")
    ops_c = (SRC / "m68kops.c").read_text()
    bodies = {m.group(1): m.group(2) for m in
              re.finditer(r'^(?:static )?void (m68k_op_\w+)\(void\)\n\{(.*?)^\}', ops_c, re.M | re.S)}
    names = sorted(bodies)
    with tempfile.TemporaryDirectory() as t:
        t = Path(t)
        (t / "dump.c").write_text(
            '#include "m68kops.c"\n#include <stdio.h>\n'
            'struct {void (*f)(void); const char *n;} N[] = {\n'
            + "".join(f'{{{n}, "{n}"}},\n' for n in names) + '};\n'
            'extern void (*m68ki_instruction_jump_table[0x10000])(void);\n'
            'extern unsigned char m68ki_cycles[][0x10000];\n'
            'int main(void){ m68ki_build_opcode_table(); int nn = sizeof N / sizeof N[0];\n'
            ' for (int i = 0; i < 0x10000; i++) { const char *nm = "?";\n'
            '  for (int j = 0; j < nn; j++) if (N[j].f == m68ki_instruction_jump_table[i]) { nm = N[j].n; break; }\n'
            '  printf("%s %d\\n", nm, m68ki_cycles[0][i]); } return 0; }\n')
        (t / "stubs.c").write_text(
            '#include "m68k.h"\n'
            'unsigned int m68k_read_memory_8(unsigned int a){(void)a;return 0;}\n'
            'unsigned int m68k_read_memory_16(unsigned int a){(void)a;return 0;}\n'
            'unsigned int m68k_read_memory_32(unsigned int a){(void)a;return 0;}\n'
            'void m68k_write_memory_8(unsigned int a, unsigned int v){(void)a;(void)v;}\n'
            'void m68k_write_memory_16(unsigned int a, unsigned int v){(void)a;(void)v;}\n'
            'void m68k_write_memory_32(unsigned int a, unsigned int v){(void)a;(void)v;}\n'
            'unsigned int m68k_read_disassembler_8(unsigned int a){(void)a;return 0;}\n'
            'unsigned int m68k_read_disassembler_16(unsigned int a){(void)a;return 0;}\n'
            'unsigned int m68k_read_disassembler_32(unsigned int a){(void)a;return 0;}\n'
            'void neo_reset_instr(void){}\n')
        subprocess.run(["gcc", "-O1", "-w", f"-I{SRC}", "-o", str(t / "dump"), str(t / "dump.c"),
                        str(SRC / "m68kcpu.c"), str(SRC / "m68kdasm.c"), str(SRC / "softfloat" / "softfloat.c"),
                        str(t / "stubs.c"), "-lm"], check=True, cwd=SRC)
        rows = subprocess.run([str(t / "dump")], capture_output=True, text=True, check=True).stdout.split("\n")
    rows = [r.split() for r in rows if r.strip()]
    assert len(rows) == 0x10000
    final = []
    for name, cyc in rows:
        cyc = int(cyc)
        n = name[len("m68k_op_"):]
        if cyc == 0 and n not in ("reset", "move16_32"):
            rest = strip_guards(bodies[name])
            if rest.endswith("m68ki_exception_1111();") or "m68ki_exception_1111" in rest:
                n = "x_1111"
            elif "m68ki_exception_illegal" in rest:
                n = "x_illegal"
            else:
                sys.exit(f"unknown 68000 behaviour for {name}: {rest[:120]}")
        final.append((n, cyc))
    used = sorted({n for n, _ in final})
    index = {n: i for i, n in enumerate(used)}
    idx = bytearray()
    for n, _ in final:
        idx += index[n].to_bytes(2, "little")
    cyc = bytes(c for _, c in final)
    blob = base64.b64encode(lzma.compress(idx + cyc, preset=9 | lzma.PRESET_EXTREME)).decode()
    lines = ['"""Musashi 68000 decode and cycle tables (generated by emulator/build_m68k_tables.py, do not edit).',
             'M68K_NAMES[i]: handler; M68K_TABLES: lzma + base64 of 65536 little-endian handler indexes',
             'then 65536 68000 cycle counts."""',
             "M68K_NAMES = ("]
    for i in range(0, len(used), 8):
        lines.append("    " + " ".join(f'"{n}",' for n in used[i:i + 8]))
    lines.append(")")
    lines.append("M68K_TABLES = (")
    for i in range(0, len(blob), 96):
        lines.append(f"    '{blob[i:i + 96]}'")
    lines.append(")")
    (HERE / "m68k_tables.py").write_text("\n".join(lines) + "\n")
    print(f"{len(used)} handlers, {len(blob)} bytes of table -> {HERE / 'm68k_tables.py'}")


if __name__ == "__main__":
    main()
