; ------------------------------------------------------------------------
; memprobe: a3 = base, d5 = highest address line (A1..Ad5, byte offsets 1<<k).
; Out: d3 = bad data bits, d2 = bad address lines (bit k = Ak).
; Data: walking 1 and walking 0 on the base word. Address (classic 3 steps):
;  1. word at base + (1<<k) = k for every line;
;  2. base = $A5A5: a line whose word changed is stuck at 1 (the base write
;     landed there);
;  3. write each line word: if the base changes, that line is stuck at 0.
; Destroys d0-d4. No stack, no WRAM.
; ------------------------------------------------------------------------
memprobe_JsrA6:
	moveq #0,d3
	moveq #1,d4
.md:
	move.w d4,(a3)
	move.w (a3),d0
	eor.w d4,d0
	or.w d0,d3
	move.w d4,d1
	not.w d1
	move.w d1,(a3)
	move.w (a3),d0
	eor.w d1,d0
	or.w d0,d3
	add.w d4,d4
	bne.s .md
	moveq #0,d2
	tst.w d3
	bne.s .mend					; bad data bits: address results meaningless
	moveq #1,d4
.m1:
	moveq #1,d1
	lsl.l d4,d1
	move.w d4,(a3,d1.l)
	addq.w #1,d4
	cmp.w d5,d4
	bls.s .m1
	move.w #$A5A5,(a3)
	moveq #1,d4
.m2:
	moveq #1,d1
	lsl.l d4,d1
	cmp.w (a3,d1.l),d4
	beq.s .m2ok
	bset d4,d2					; stuck at 1
.m2ok:
	addq.w #1,d4
	cmp.w d5,d4
	bls.s .m2
	moveq #1,d4
.m3:
	moveq #1,d1
	lsl.l d4,d1
	move.w #$5A5A,(a3,d1.l)
	cmpi.w #$A5A5,(a3)
	beq.s .m3ok
	bset d4,d2					; stuck at 0
	move.w #$A5A5,(a3)
.m3ok:
	addq.w #1,d4
	cmp.w d5,d4
	bls.s .m3
.mend:
	RtsA6

; ------------------------------------------------------------------------
; vramprobe: d1 = base VRAM address ($0000 slow, $8000 fast), d5 = number
; of address lines (A0..Ad5-1, word offsets 1<<k). Same tests and output
; as memprobe. LSPC2 timing (neogeodev wiki, VRAM): read >= 16 CPU cycles
; after the address write (Nop2 + the read's own fetch); 16 cycles after a
; data write before a new address (Nop4). VRAMMOD = 1 (set by the caller,
; unused here: the address is set before every access). Destroys d0, d2-d4.
; ------------------------------------------------------------------------
	macro VWrite				; \1 = VRAM address (Dn), \2 = data
		move.w \1,(REG_VRAMADD).l
		move.w \2,(REG_VRAMRW).l
		Delay d0,16
	endm
	macro VRead					; \1 = VRAM address (Dn), result in d0
		move.w \1,(REG_VRAMADD).l
		Delay d0,16						; wiki "VRAM": read valid >= 16 cycles after the address (28 here)
		move.w (REG_VRAMRW).l,d0
	endm
	macro VAddr					; d0 = d1 | (1 << d4), no stack (WRAM may be bad)
		moveq #1,d0
		lsl.w d4,d0
		or.w d1,d0
	endm
vramprobe_JsrA6:
	moveq #0,d3
	moveq #1,d4
.vd:
	VWrite d1,d4
	VRead d1
	eor.w d4,d0
	or.w d0,d3
	move.w d4,d2
	not.w d2
	VWrite d1,d2
	VRead d1
	eor.w d2,d0
	or.w d0,d3
	add.w d4,d4
	bne .vd
	moveq #0,d2
	tst.w d3
	bne .vend
	moveq #0,d4
.v1:
	VAddr						; d0 = base | (1<<k)
	VWrite d0,d4
	addq.w #1,d4
	cmp.w d5,d4
	bne.s .v1
	VWrite d1,#$A5A5
	moveq #0,d4
.v2:
	VAddr
	VRead d0
	cmp.w d4,d0
	beq.s .v2ok
	bset d4,d2					; stuck at 1
.v2ok:
	addq.w #1,d4
	cmp.w d5,d4
	bne.s .v2
	moveq #0,d4
.v3:
	VAddr
	VWrite d0,#$5A5A
	VRead d1
	cmp.w #$A5A5,d0
	beq.s .v3ok
	bset d4,d2					; stuck at 0
	VWrite d1,#$A5A5
.v3ok:
	addq.w #1,d4
	cmp.w d5,d4
	bne.s .v3
.vend:
	RtsA6

; ------------------------------------------------------------------------
; memReport: prints the end of a table line, then what to suspect and the
; test to run next. d3 = bad data bits, d2 = bad address lines (bit k = Ak),
; d5 = F_xxx flag of the part (palette: bit 13 of d2 = bank select).
; Sets the flag in d7 on failure. Destroys d0-d4, a0-a5 (a5 = saved link,
; a4 = data bits, a3 = address lines).
; ------------------------------------------------------------------------
	macro BitList				; \1 = mask register (a3/a4), \2 = letter: " D3 D5..."
		move.l \1,d1
		moveq #\2,d3
		JsrA6 printBitList		; keeps a3, a4, a5, d5, d7
	endm
memReport_JsrA6:
	movea.l a6,a5
	movea.l d2,a3
	movea.l d3,a4
	move.w d3,d0
	or.w d2,d0
	bne.s .bad
	PrintLn "OK"
	jmp (a5)
.bad:
	bset d5,d7
	Print "FAIL   "
	move.l a4,d0
	tst.w d0
	beq .lines
	Print " data"
	BitList a4,'D'
.lines:
	move.l a3,d0
	bclr #13,d0					; Z = bit 13 was 0
	beq.s .noBank
	cmp.w #F_PAL,d5
	bne.s .noBank				; WRAM: bit 13 is line A13
	bset #31,d5					; palette: bank select, printed apart
	movea.l d0,a3
.noBank:
	move.l a3,d0
	tst.w d0
	beq.s .bank
	Print " address"
	BitList a3,'A'
.bank:
	btst #31,d5
	beq.s .hint
	bclr #31,d5
	Print " bank-select"
.hint:
	PrintLn ""
	move.l a4,d0
	cmp.w #F_WRAM,d5
	bne .hPal
	tst.w d0
	beq .hwAddr
	and.w #$00FF,d0
	beq .hwUpper
	move.l a4,d0
	and.w #$FF00,d0
	beq .hwLower
	PrintLn "     -> both bytes: 68000 data bus, NEO-C1, both WRAM chips. Next: TestWRAM"
	jmp (a5)
.hwUpper:
	PrintLn "     -> D8-D15: upper WRAM chip, or NEO-C1 WRU/WWU. Next: TestWRAM"
	jmp (a5)
.hwLower:
	PrintLn "     -> D0-D7: lower WRAM chip, or NEO-C1 WRL/WWL. Next: TestWRAM"
	jmp (a5)
.hwAddr:
	PrintLn "     -> WRAM address pins, 68000 address bus. Next: TestWRAM"
	jmp (a5)
.hPal:
	cmp.w #F_PAL,d5
	bne .hSlow
	tst.w d0
	beq .hpAddr
	PrintLn "     -> palette RAM chip of those bits, NEO-G0 (data buffer, write enable). Next: TestPRAM, TestDAC"
	jmp (a5)
.hpAddr:
	PrintLn "     -> palette RAM address (NEO-B1 address switch), bank: system latch. Next: TestPRAM"
	jmp (a5)
.hSlow:
	cmp.w #F_VRAML,d5
	bne .hFast
	PrintLn "     -> slow VRAM chip of those bits/lines, LSPC2-A2 B/E bus. Next: TestVRAM"
	jmp (a5)
.hFast:
	PrintLn "     -> fast VRAM chip of those bits/lines, LSPC2-A2 C/F bus. Next: TestVRAM"
	jmp (a5)

