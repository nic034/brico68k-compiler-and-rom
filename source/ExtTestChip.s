	; --- frame: CPU cycles per frame (24 MHz to the LSPC2 vs 12 MHz 68KCLK) ---
	WatchDog
	move.w #LINE_MASK,d3
	move.l #20000,d4
.fTop:
	WatchDog
	move.w (REG_LSPCMODE).l,d0
